// Storage for uploaded medicine images.
//
// Locally (`node server.js`) images live in backend/uploads and are served by
// express.static. On Netlify the API runs as a serverless function whose disk is
// read-only and short-lived, so multer writes to the temp directory and the
// bytes are then stored in MongoDB (the `medicineimages` collection). Reading
// therefore works on any host — laptop, Render, Netlify — and survives
// redeploys, because the database is the durable store.
//
// Lookup order for GET /uploads/:name in a serverless function:
//   1. MongoDB (`medicineimages`)   — uploads and images mirrored by seed:data
//   2. Netlify Blobs                — images uploaded before MongoDB storage
//   3. backend/uploads on disk      — demo SVGs committed to the repository
//
// Demo images generated by `npm run seed:data` are committed to the repository
// (backend/uploads/seed-*.svg) *and* mirrored into MongoDB, so a fresh Atlas
// database serves them even when the function bundle does not carry the files.
const express = require('express');
const fs = require('fs');
const os = require('os');
const path = require('path');
const MedicineImage = require('../models/MedicineImage');

const SERVERLESS = process.env.MEDITRACK_SERVERLESS === '1';
const STORE_NAME = 'medicine-images';
// Filenames are generated by multer (medicine-…) or the seeder (seed-…), so this
// also keeps a hostile ":name" value away from the file system and Mongo query.
const SAFE_NAME_RE = /^[A-Za-z0-9][A-Za-z0-9._-]*$/;

// Read/write location for multer uploads.
const UPLOADS_DIR = SERVERLESS
  ? path.join(os.tmpdir(), 'meditrack-uploads')
  : path.join(__dirname, '..', 'uploads');

if (!fs.existsSync(UPLOADS_DIR)) {
  fs.mkdirSync(UPLOADS_DIR, { recursive: true });
}

const MIME_TYPES = {
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.gif': 'image/gif',
  '.webp': 'image/webp',
};

function mimeFor(filename) {
  return MIME_TYPES[path.extname(filename).toLowerCase()] || 'application/octet-stream';
}

function blobStore() {
  // Loaded lazily so local development and tests never need @netlify/blobs.
  const { getStore } = require('@netlify/blobs');
  return getStore({ name: STORE_NAME, consistency: 'strong' });
}

let cachedBundledDir;
/**
 * Directory that holds the demo images committed to the repository.
 *
 * Under the Netlify bundler the function code does not run from `backend/`, so
 * `path.join(__dirname, '..', 'uploads')` can point at a directory that does not
 * exist. Try the plausible locations once and remember the first that is real.
 */
function bundledUploadsDir() {
  if (cachedBundledDir !== undefined) return cachedBundledDir;

  const candidates = [
    path.join(__dirname, '..', 'uploads'),
    path.join(process.cwd(), 'backend', 'uploads'),
    path.join(process.cwd(), 'uploads'),
  ];
  // Bundlers disagree about where `__dirname` ends up; walk up from it too.
  let dir = __dirname;
  for (let depth = 0; depth < 5; depth += 1) {
    candidates.push(path.join(dir, 'backend', 'uploads'), path.join(dir, 'uploads'));
    dir = path.dirname(dir);
  }

  for (const candidate of candidates) {
    try {
      if (fs.statSync(candidate).isDirectory()) {
        cachedBundledDir = candidate;
        return cachedBundledDir;
      }
    } catch {
      // Not there — keep looking.
    }
  }
  cachedBundledDir = path.join(__dirname, '..', 'uploads');
  return cachedBundledDir;
}

/** Store (or replace) an image in MongoDB. Used by the serverless upload path. */
async function saveImageToDb(filename, data, contentType) {
  const buffer = Buffer.isBuffer(data) ? data : Buffer.from(data);
  await MedicineImage.updateOne(
    { filename },
    {
      $set: {
        filename,
        contentType: contentType || mimeFor(filename),
        sizeBytes: buffer.length,
        data: buffer,
      },
    },
    { upsert: true, setDefaultsOnInsert: true }
  );
}

/**
 * Read one image from MongoDB (bytes included), or `null` when it is absent.
 *
 * `lean()` returns a BSON `Binary` for a Buffer field, so its bytes are copied
 * out of `binary.buffer`; a hydrated document would return a real Buffer.
 */
async function readImageFromDb(filename) {
  const row = await MedicineImage.findOne({ filename }).select('+data').lean();
  if (!row) return null;
  const data = Buffer.isBuffer(row.data) ? row.data : Buffer.from(row.data.buffer);
  return { ...row, data };
}

/** Delete one image from MongoDB, ignoring "already gone" errors. */
async function deleteImageFromDb(filename) {
  return MedicineImage.deleteOne({ filename });
}

/** Read an image from the legacy Netlify Blobs store, or `null`. */
async function readImageFromBlob(name) {
  try {
    const entry = await blobStore().getWithMetadata(name, { type: 'arrayBuffer' });
    if (!entry) return null;
    return {
      data: Buffer.from(entry.data),
      contentType: entry.metadata?.contentType || mimeFor(name),
    };
  } catch {
    // Blobs is not configured (local run, tests) or is unavailable — fall back.
    return null;
  }
}

/** Read a demo image bundled with the deployment, or `null`. */
async function readBundledImage(name) {
  const filePath = path.join(bundledUploadsDir(), name);
  try {
    const data = await fs.promises.readFile(filePath);
    return { data, contentType: mimeFor(name) };
  } catch {
    return null;
  }
}

/** Send an image with long-lived caching (file names are unique per upload). */
function sendImage(res, { data, contentType }, { immutable = true } = {}) {
  res.set('Content-Type', contentType || 'application/octet-stream');
  res.set('Content-Length', String(data.length));
  res.set(
    'Cache-Control',
    immutable ? 'public, max-age=31536000, immutable' : 'public, max-age=3600'
  );
  return res.send(data);
}

/** Middleware: after multer, save the uploaded file's bytes (serverless only). */
async function persistUpload(req, res, next) {
  if (!SERVERLESS || !req.file) return next();
  try {
    const data = await fs.promises.readFile(req.file.path);
    await saveImageToDb(req.file.filename, data, req.file.mimetype);
    fs.unlink(req.file.path, () => {});
    return next();
  } catch (err) {
    return next(err);
  }
}

/** Delete a stored image, ignoring "already gone" errors. */
function removeUpload(filename) {
  if (!filename) return;
  // MongoDB is the durable store on Netlify and a harmless no-op locally.
  deleteImageFromDb(filename).catch(() => {});
  if (SERVERLESS) {
    blobStore()
      .delete(filename)
      .catch(() => {});
    return;
  }
  fs.unlink(path.join(UPLOADS_DIR, filename), () => {});
}

/**
 * Router that serves stored images under /uploads.
 *
 * @param {{ serverless?: boolean }} [options] `serverless` overrides the mode
 *   detected from MEDITRACK_SERVERLESS (used by the tests).
 */
function serveUploads({ serverless = SERVERLESS } = {}) {
  if (!serverless) return express.static(UPLOADS_DIR);

  const router = express.Router();
  router.get('/:name', async (req, res, next) => {
    // basename() prevents `..%2F` traversal in a function URL.
    const name = path.basename(String(req.params.name || ''));
    if (!name || !SAFE_NAME_RE.test(name)) return res.status(404).end();

    try {
      // 1. MongoDB: uploads and the demo images mirrored by `npm run seed:data`.
      const stored = await readImageFromDb(name);
      if (stored?.data) {
        return sendImage(res, {
          data: Buffer.from(stored.data),
          contentType: stored.contentType,
        });
      }

      // 2. Netlify Blobs: images uploaded before MongoDB became the store.
      const fromBlob = await readImageFromBlob(name);
      if (fromBlob) return sendImage(res, fromBlob);

      // 3. A demo image shipped with the repository (see `npm run seed:data`).
      const bundled = await readBundledImage(name);
      if (bundled) return sendImage(res, bundled, { immutable: false });

      return res.status(404).end();
    } catch (err) {
      return next(err);
    }
  });
  return router;
}

module.exports = {
  UPLOADS_DIR,
  bundledUploadsDir,
  saveImageToDb,
  readImageFromDb,
  deleteImageFromDb,
  persistUpload,
  removeUpload,
  serveUploads,
};

